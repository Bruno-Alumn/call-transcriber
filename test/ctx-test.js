// Archive / unarchive / delete via right-click, on a copy of real transcripts.
const { chromium } = require('playwright');
const { spawn, execSync } = require('child_process');
const path = require('path'), fs = require('fs');
const SCRATCH = process.argv[2], OUT = path.join(SCRATCH, 'tx-ctx');
(async () => {
  const srv = spawn(path.join(__dirname, '..', 'server', '.venv', 'bin', 'python'), [path.join(__dirname, '..', 'server', 'server.py'), '--port', '8766', '--out', OUT]);
  let log = ''; srv.stdout.on('data', (d) => (log += d)); srv.stderr.on('data', (d) => (log += d));
  while (!log.includes('Dashboard:')) await new Promise((r) => setTimeout(r, 300));
  const b = await chromium.launch(); const page = await b.newPage({ viewport: { width: 1320, height: 860 }, colorScheme: 'dark' });
  page.on('pageerror', (e) => console.log('PAGE ERROR', e.message));
  await page.goto('http://127.0.0.1:8766/'); await page.waitForTimeout(1500);
  const servers = async () => page.evaluate(() => [...document.querySelectorAll('#calls > .srv .nm')].map((e) => e.textContent));
  const archCount = async () => page.evaluate(() => document.querySelector('#archhead .ct')?.textContent || '0');
  console.log('START servers:', await servers());
  await page.click('.srv:has-text("Before channel tracking")', { button: 'right' });
  await page.screenshot({ path: path.join(SCRATCH, 'ctx-menu.png') });
  await page.click('#ctx button[data-a="archive"]'); await page.waitForTimeout(600);
  console.log('ARCHIVE  servers:', await servers(), '| archived calls:', await archCount());
  await page.click('#archhead'); await page.waitForTimeout(300);
  await page.screenshot({ path: path.join(SCRATCH, 'ctx-archived.png') });
  await page.click('.archived-tree .srv', { button: 'right' });
  await page.click('#ctx button[data-a="unarchive"]'); await page.waitForTimeout(600);
  console.log('UNARCHIVE servers:', await servers(), '| archived calls:', await archCount());
  const linesBefore = execSync(`cat ${OUT}/*.jsonl | wc -l`).toString().trim();
  await page.click('.chn:has-text("Unknown channel")', { button: 'right' });
  await page.click('#ctx button[data-a="delete"]'); await page.waitForTimeout(500);
  await page.screenshot({ path: path.join(SCRATCH, 'ctx-confirm.png') });
  console.log('CONFIRM TEXT:', (await page.textContent('.modal')).replace(/\s+/g, ' ').slice(0, 220));
  await page.click('.modal button.danger'); await page.waitForTimeout(800);
  console.log('DELETE   servers:', await servers());
  console.log('trash files:', fs.readdirSync(path.join(OUT, '.trash')).join(', '));
  const mdLeft = execSync(`grep -c '^\\*\\*\\[' ${OUT}/2026-11-19.md || true`).toString().trim();
  console.log('yesterday md transcript lines left:', mdLeft, '| jsonl lines before/after:', linesBefore, execSync(`cat ${OUT}/*.jsonl | wc -l`).toString().trim());
  const forged = execSync(`curl -s -o /dev/null -w "%{http_code}" "http://127.0.0.1:8766/api/delete?kind=server&key=unknown"`).toString();
  const rebinding = execSync(`curl -s -o /dev/null -w "%{http_code}" -H "Host: evil.example" -H "X-CT: 1" "http://127.0.0.1:8766/api/calls"`).toString();
  console.log('delete without app header ->', forged, '| foreign Host header ->', rebinding);
  await b.close(); srv.kill();
})().catch((e) => { console.error(e); process.exit(1); });
